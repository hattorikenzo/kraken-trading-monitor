'use strict';
const assert=require('node:assert/strict');
const {validSymbols,fromSeries}=require('../stock-feed.js');
assert.deepEqual(validSymbols('NASDAQ:NVDA, NYSE:KO'),['NASDAQ:NVDA','NYSE:KO']);
assert.throws(()=>validSymbols(''),/1 a 8/);
assert.throws(()=>validSymbols('bad'),/Formato/);
assert.throws(()=>validSymbols(Array(9).fill('NASDAQ:NVDA').join(',')),/1 a 8/);
const today=new Date().toISOString().slice(0,10);
const values=Array.from({length:45},(_,i)=>({datetime:new Date(Date.now()-i*86400000).toISOString().slice(0,10),close:String(100-i*.1),volume:'10000'}));
values[0].datetime=today;
const row=fromSeries('NASDAQ:NVDA',{values},1.6);
assert.equal(row.symbol,'NASDAQ:NVDA');
assert.equal(row.spreadMissing,true);
assert.ok(row.rsi>=0&&row.rsi<=100);
assert.throws(()=>fromSeries('NASDAQ:NVDA',{status:'error',message:'quota'},1.6),/quota/);
assert.throws(()=>fromSeries('NASDAQ:NVDA',{values:values.slice(0,5)},1.6),/30 sedute/);
const stale=values.map((x,i)=>({...x,datetime:new Date(Date.now()-(i+20)*86400000).toISOString().slice(0,10)}));
assert.throws(()=>fromSeries('NASDAQ:NVDA',{values:stale},1.6),/non recente/);
console.log('Stock feed: 10 assertions PASS');
